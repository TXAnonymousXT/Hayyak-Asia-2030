export const getEventById = (id: string): Event | undefined => {
  return events.find(event => event.id === id);
};

export const getEventsByVenue = (venueId: string): Event[] => {
  return events.filter(event => event.venueId === venueId);
};

export const getEventsBySport = (sport: string): Event[] => {
  return events.filter(event => event.sport.toLowerCase() === sport.toLowerCase());
};

export const getFeaturedEvents = (): Event[] => {
  return events.filter(event => event.isFeatured);
};
